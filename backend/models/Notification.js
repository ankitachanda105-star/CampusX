const mongoose = require('mongoose');

const NotificationSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    type: {
      type: String,
      enum: ['QUEUE_ALERT', 'SERVICE_UPDATE', 'SYSTEM_ALERT'],
      default: 'QUEUE_ALERT',
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
    read: {
      type: Boolean,
      default: false,
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

// Mongoose collection name explicitly set to 'notifications'
const Notification = mongoose.model('Notification', NotificationSchema, 'notifications');

module.exports = {
  Notification,
};
